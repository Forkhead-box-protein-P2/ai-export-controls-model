"""Annual payoff flows and their aggregation under explicit normative weights.

The payoff is a vector first. Aggregation happens only in ``weight_vector`` and
``aggregate``, with weights that belong to the analyst's values, not to the world model.

There is no separate prize for "winning". A first mover's gain is the contestable
post-transition surplus it captures (``lead_*``) and the coercion its rival is exposed to
(``sec_*``); both are generated by the modelled lead, capture share and persistence.
Baseline GDP is identical across policies and is left out, so every reported value is a
difference from that common baseline.
"""
from __future__ import annotations

import numpy as np

from .state import COMPONENTS

EPS = 1e-12
MONEY_ACTORS = ("us", "cn", "row")


def base_uplift(avail, avail0, inf, inf0, P):
    """Pre-transition GDP uplift from useful AI: capability available to the economy
    combined with the inference compute to deploy it, saturating at ``uplift_max``."""
    u = np.maximum(P.cap_w * (avail - avail0) + P.inf_w * np.log(np.maximum(inf, EPS) / inf0), 0.0)
    return P.uplift_max * (1.0 - np.exp(-u / P.uplift_scale))


def flows(s: dict, P) -> dict:
    """Undiscounted payoff flows for one year. ``s`` holds the year's state."""
    gdp = {a: s[f"gdp_{a}"] for a in MONEY_ACTORS}
    up = {a: s[f"base_up_{a}"] for a in MONEY_ACTORS}
    tai = {a: s[f"tai_up_{a}"] for a in MONEY_ACTORS}
    O, T, adv = s["O"], s["T"], s["adv"]
    us_leads, cn_leads = s["leader"] == 1, s["leader"] == 2
    f = {}

    # AI-driven output, plus spillovers: ideas are non-rival, so part of each economy's
    # AI-driven output raises the others', in proportion to their size.
    own = {a: gdp[a] * (up[a] + tai[a]) for a in MONEY_ACTORS}
    gdp_sum = gdp["us"] + gdp["cn"] + gdp["row"]
    ai = {a: own[a] + P.sci_spill * (sum(own.values()) - own[a]) * gdp[a] / gdp_sum
          for a in MONEY_ACTORS}
    for a in MONEY_ACTORS:
        f[f"ai_{a}"] = ai[a]

    # Trade: chip export profit net of displaced sales, Chinese chip exports that compete
    # with Western ones, retaliation, decoupling and subsidy costs.
    unit_price = P.w_rev0 / P.w0 / np.maximum(s["cu_chip"], EPS)
    profit = s["legal_imports"] * unit_price * P.chip_margin * (1.0 - s["scarcity_t"])
    cn_export_profit = s["cn_exports"] * unit_price * P.chip_margin
    lost = P.cn_export_disp * cn_export_profit
    friction = P.tens_cost * np.maximum(T - P.t_floor, 0.0)
    f["trade_us"] = (P.us_capture * (profit - lost) - P.ret_cost * s["y_ret"] * gdp["us"]
                     - friction * gdp["us"])
    f["trade_cn"] = (cn_export_profit - friction * gdp["cn"]
                     - P.sub_cost * (s["y_rd"] - 1.0) * gdp["cn"])
    f["trade_row"] = (1.0 - P.us_capture) * (profit - lost) - 0.5 * friction * gdp["row"]

    # Openness: wider access raises useful AI everywhere. Closed-provider markups are paid
    # by US and third-country users (a deadweight loss on top) and received by US providers;
    # the receipts are a separate component so that their weight is a visible choice.
    markup = P.markup_max * (1.0 - O)
    rent = {a: markup * P.spend_share * own[a] for a in ("us", "row")}
    dwl = {a: 0.5 * markup * rent[a] for a in ("us", "row")}
    gain = {a: gdp[a] * up[a] * P.open_boost * O for a in MONEY_ACTORS}
    f["open_us"] = gain["us"] - rent["us"] - dwl["us"]
    f["open_cn"] = gain["cn"]
    f["open_row"] = gain["row"] - rent["row"] - dwl["row"]
    f["rent_us"] = rent["us"] + rent["row"]

    # Durable lead: the leader captures part of the others' contestable post-transition surplus.
    pool = {a: P.contest_share * gdp[a] * tai[a] for a in MONEY_ACTORS}
    keep = 1.0 - P.capture_dwl
    f["lead_us"] = np.where(us_leads, keep * adv * (pool["cn"] + pool["row"]),
                            np.where(cn_leads, -adv * pool["us"], 0.0))
    f["lead_cn"] = np.where(cn_leads, keep * adv * (pool["us"] + pool["row"]),
                            np.where(us_leads, -adv * pool["cn"], 0.0))
    f["lead_row"] = -adv * pool["row"]

    # Institutions: a durable order that turns out adverse (concentrated, unaccountable
    # control) costs every economy a share of output in proportion to the advantage held.
    for a in MONEY_ACTORS:
        f[f"inst_{a}"] = -P.adverse_cost * adv * s["adverse"] * (gdp[a] + ai[a])

    # War and catastrophe losses apply to total output (baseline GDP plus AI-driven output).
    # A catastrophe has no feedback on the simulated state, so its loss enters as an exact
    # expectation given the hazard path (p_cat), which removes most Monte Carlo noise.
    in_war = s["in_war"]
    sev = s["war_sev"]
    war_cost = {"us": P.war_cost_us, "cn": P.war_cost_cn, "row": P.war_cost_row}
    for a in MONEY_ACTORS:
        total = gdp[a] + ai[a]
        loss = np.where(in_war, war_cost[a] * sev, 0.0) + np.where(s["escalated"], P.escal_severity, 0.0)
        f[f"war_{a}"] = -np.minimum(loss, 1.0) * total
        f[f"cat_{a}"] = -P.cat_severity * s["p_cat"] * total

    # Security: exposure to coercion by a rival with a durable advantage, plus the
    # pre-transition military value of a capability edge.
    edge = np.where(s["arrived"], 0.0, P.pre_sec * np.tanh(s["lag_years"] / P.det_tau))
    f["sec_us"] = -np.where(cn_leads, adv, 0.0) + edge
    f["sec_cn"] = -np.where(us_leads, adv, 0.0) - edge

    # Openness and pluralism index; integration and trust index.
    f["liberty"] = (P.lib_open * O + P.lib_plural * (1.0 - adv)
                    - P.lib_adverse * adv * s["adverse"])
    f["trust"] = s["I"] - T
    f["advyrs_us"] = np.where(us_leads, adv, 0.0)
    f["advyrs_cn"] = np.where(cn_leads, adv, 0.0)
    f["sov_cn"] = s["k_mean"]
    return f


def terminal_factor(P):
    """Present-value multiple applied to final-year flows for the years after the horizon."""
    q = P.terminal_persist / (1.0 + P.discount_rate)
    return q * (1.0 - q ** P.terminal_years) / (1.0 - q)


def weight_vector(w: dict) -> np.ndarray:
    """Turn a normative weight set into one weight per payoff component."""
    money = w["money"]
    out = np.zeros(len(COMPONENTS))
    for k, name in enumerate(COMPONENTS):
        head, _, actor = name.rpartition("_")
        if head in ("ai", "trade", "open", "lead", "inst"):
            out[k] = money[actor]
        elif head == "rent":
            out[k] = money[actor] * w.get("rent_weight", 1.0)
        elif head == "war":
            out[k] = money[actor] * (1.0 + w.get("war_extra", 0.0))
        elif head == "cat":
            out[k] = money[actor] * (1.0 + w.get("cat_extra", 0.0))
        elif head == "sec":
            out[k] = w.get(f"v_sec_{actor}", 0.0)
        elif head == "advyrs":
            out[k] = w.get(f"lead_extra_{actor}", 0.0)
        elif head == "sov":
            out[k] = w.get(f"v_sov_{actor}", 0.0)
        elif name == "liberty":
            out[k] = w.get("v_liberty", 0.0)
        elif name == "trust":
            out[k] = w.get("v_trust", 0.0)
    return out


def aggregate(comps: np.ndarray, w: dict) -> np.ndarray:
    """Scalar value per simulation under a weight set (trillions of 2026 dollars)."""
    return comps @ weight_vector(w)
